// 形式の検査（src/masters/build.ts）は、ここの項目数・型・値の区分に合わない行が 1 つでもあれば、その表を作らない（別の版のレイアウトを黙って読まない）

/** 項目の型。check に合わない値が 1 つでもあれば、その表を作らない。as は SQLite に入れる形 */
export type ColType = { check: RegExp; as: "text" | "int" | "real" };

/** 固定桁の数字（コード） */
const code = (len: number): ColType => ({ check: new RegExp(`^\\d{${len}}$`), as: "text" });
/** 整数（数字モードは前ゼロを省略して記録される） */
const int: ColType = { check: /^\d{1,9}$/, as: "int" };
/** 点数・金額（整数部と小数部 2 桁。[基] p28 項番12 ほか） */
const num: ColType = { check: /^\d{1,10}(\.\d{1,5})?$/, as: "real" };
/** 年月日（西暦 8 桁。99999999＝廃止していない、00000000＝設定なし を含む） */
const date: ColType = { check: /^\d{8}$/, as: "text" };
/** 年月日（省略あり） */
const dateOpt: ColType = { check: /^(\d{8})?$/, as: "text" };
/** 仕様書に挙がっている値のどれか（前ゼロの有無はファイルのまま） */
const oneOf = (...values: string[]): ColType => ({ check: new RegExp(`^(${values.join("|")})$`), as: "text" });
const text: ColType = { check: /^[^\u0000-\u001f]*$/, as: "text" };
/** 年齢の上下限（[基] p34 項番41・42）：数字 2 桁（00＝制限なし）か、AA 生後28日／AE 生後90日／B3・B6・BF・BK＝3・6・15・20 歳に達した日の翌月の 1 日／MG 未就学児 */
const age: ColType = { check: /^(\d{2}|AA|AE|B3|B6|BF|BK|MG)$/, as: "text" };
/** 変更区分（各マスターの項番1。[基] p27 ほか）：0 前と同じ／1 抹消／2 復活／3 新規／5 変更／9 廃止（次の更新で消える） */
const change = oneOf("0", "1", "2", "3", "5", "9");
/** チェックマスタの年齢（[チ] p18 項番6・7）：XXX.XX。下限なし 000.00、上限なし 999.99 */
const ageDecimal: ColType = { check: /^\d{3}\.\d{2}$/, as: "real" };

/** 取り込む項目。item は仕様書の項番（1 起算。配列は繰り返しの項目で、0 でない値を "," でつないで 1 列にする） */
export type Column = { item: number | number[]; col: string; name: string; type: ColType };
const c = (item: number | number[], col: string, name: string, type: ColType): Column => ({ item, col, name, type });

export type TableLayout = {
  /** config/masters.json の files の layout が指す名前（ファイル名の形・項目数・文字コードは config の側で持つ） */
  id: string;
  /** masters.db の表の名前 */
  table: string;
  /** 見出しの行があるファイルは、その 1 行め（項目名。違えば別のレイアウトとして断る） */
  header?: string[];
  columns: Column[];
  /** ファイルごとに決まる列（背反の 4 つのファイルを 1 つの表に入れるための tani） */
  fixed?: Record<string, number>;
  /** 索引を張る列（snapshot の次に並べる） */
  index: string[][];
  /** 最初の索引を一意にする（1 枚の中で、同じコードの行は 1 つ） */
  unique?: true;
};

